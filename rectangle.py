def area(a, b):
    """!Calculates an area of a rectangle

    @param a Length of one edge
    @param b Length of other edge

    @return a * b
    """
    return a * b


def perimeter(a, b):
    """!Calculates a perimeter of a rectangle

    @param a Length of one edge
    @param b Length of other edge

    @return 2 * (a + b)
    """
    return 2 * (a + b)
